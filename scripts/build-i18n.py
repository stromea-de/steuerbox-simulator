#!/usr/bin/env python3
"""Bundle source-controlled offline dictionaries. Standard library only."""
import json
from pathlib import Path
ROOT=Path(__file__).resolve().parent.parent
base=ROOT/'internal/webui/assets'
def bundle():
 data={code:json.loads((base/'i18n'/f'{code}.json').read_text()) for code in ['de','en','pl','ru','uk','tr','ro']}
 keys=set(data['de'])
 for code,values in data.items():
  if set(values)!=keys or any(not isinstance(v,str) or not v.strip() for v in values.values()):raise ValueError('Incomplete dictionary: '+code)
 return '/* Embedded offline dictionaries; generated by scripts/build-i18n.py. */\nwindow.StromeaDictionaries='+json.dumps(data,ensure_ascii=False,separators=(',',':')).replace('<','\\u003c')+';\n'
if __name__=='__main__':(base/'i18n-data.js').write_text(bundle())
